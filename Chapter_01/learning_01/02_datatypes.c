#include <stdio.h>

int main() {

    int a = 10;
    printf("Integer value is %d\n", a);

    float b = 4.5;
    printf("Float value is %f\n", b);

    char c = '@';
    printf("Character value is %c\n", c);

    double e = 3545.14;
    printf("Double value is %lf\n", e);

    void *ptr = NULL;
    printf("Pointer value is %p\n", ptr);

    return 0;
}